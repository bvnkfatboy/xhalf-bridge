use crate::models::ComposerProjectDto;
use crate::AppState;
use rusqlite::params;
use serde_json::Value;
use tauri::State;

fn row_to_project(row: &rusqlite::Row) -> rusqlite::Result<ComposerProjectDto> {
    let json_str: String = row.get("project_json")?;
    Ok(ComposerProjectDto {
        id: row.get("id")?,
        name: row.get("name")?,
        project: serde_json::from_str(&json_str).unwrap_or(Value::Null),
        canvas_width: row.get("canvas_width")?,
        canvas_height: row.get("canvas_height")?,
        created_at: row.get("created_at")?,
        updated_at: row.get("updated_at")?,
    })
}

#[tauri::command]
pub fn save_composer_project(
    state: State<'_, AppState>,
    id: Option<i64>,
    name: String,
    project: Value,
    canvas_width: i64,
    canvas_height: i64,
) -> Result<i64, String> {
    let conn = state.db.lock().unwrap();
    let now = crate::util::now_ms();
    match id {
        Some(pid) => {
            let updated = conn
                .execute(
                    "UPDATE composer_projects SET name = ?1, project_json = ?2, canvas_width = ?3, canvas_height = ?4, updated_at = ?5 WHERE id = ?6",
                    params![name, project.to_string(), canvas_width, canvas_height, now, pid],
                )
                .map_err(|e| e.to_string())?;
            if updated == 0 {
                return Err("project not found".into());
            }
            Ok(pid)
        }
        None => {
            conn.execute(
                "INSERT INTO composer_projects (name, project_json, canvas_width, canvas_height, created_at, updated_at)
                 VALUES (?1, ?2, ?3, ?4, ?5, ?5)",
                params![name, project.to_string(), canvas_width, canvas_height, now],
            )
            .map_err(|e| e.to_string())?;
            Ok(conn.last_insert_rowid())
        }
    }
}

#[tauri::command]
pub fn list_composer_projects(state: State<'_, AppState>) -> Result<Vec<ComposerProjectDto>, String> {
    let conn = state.db.lock().unwrap();
    let mut stmt = conn
        .prepare("SELECT * FROM composer_projects ORDER BY updated_at DESC")
        .map_err(|e| e.to_string())?;
    let rows = stmt.query_map([], row_to_project).map_err(|e| e.to_string())?;
    Ok(rows.flatten().collect())
}

#[tauri::command]
pub fn get_composer_project(state: State<'_, AppState>, id: i64) -> Result<ComposerProjectDto, String> {
    let conn = state.db.lock().unwrap();
    conn.query_row("SELECT * FROM composer_projects WHERE id = ?1", [id], row_to_project)
        .map_err(|e| e.to_string())
}

#[tauri::command]
pub fn delete_composer_project(state: State<'_, AppState>, id: i64) -> Result<(), String> {
    let conn = state.db.lock().unwrap();
    conn.execute("DELETE FROM composer_projects WHERE id = ?1", [id]).map_err(|e| e.to_string())?;
    Ok(())
}

/// Save canvas-generated bytes (composer / contact sheet export) to disk.
#[tauri::command]
pub fn save_canvas_export(state: State<'_, AppState>, data_url: String, dest_path: String) -> Result<(), String> {
    use base64::Engine;
    let (mime, b64) = data_url
        .split_once(";base64,")
        .ok_or("invalid data url")?;
    let _ = mime;
    let bytes = base64::engine::general_purpose::STANDARD
        .decode(b64)
        .map_err(|e| format!("decode: {e}"))?;
    let _ = &state; // state kept for future bookkeeping (export history)
    std::fs::write(&dest_path, bytes).map_err(|e| format!("write: {e}"))?;
    Ok(())
}
